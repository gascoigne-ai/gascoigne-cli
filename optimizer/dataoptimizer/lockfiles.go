package dataoptimizer

import (
	"cmp"
	"fmt"
	"strings"

	"github.com/gascoigne-ai/gascoigne-cli/internal/lazyre"
)

var (
	pnpmPkg    = lazyre.New(`^  '?/?(@?[^@'\s]+)@([^':\s(]+)'?:$`)
	pubName    = lazyre.New(`^  (\S+):$`)
	pubVer     = lazyre.New(`^    version: "?([^"\s]+)"?$`)
	mixHex     = lazyre.New(`^\s*"([^"]+)": \{:hex, :[^,]+, "([^"]+)"`)
	mixGit     = lazyre.New(`^\s*"([^"]+)": \{:git, "[^"]*", "([0-9a-f]{7})`)
	podSpec    = lazyre.New(`^  - (\S+) \(([^)]+)\)`)
	spmName    = lazyre.New(`^\s*"(?:identity|package)"\s*:\s*"([^"]+)"`)
	spmVersion = lazyre.New(`^\s*"version"\s*:\s*"([^"]+)"`)
	spmBranch  = lazyre.New(`^\s*"branch"\s*:\s*"([^"]+)"`)
	spmRev     = lazyre.New(`^\s*"revision"\s*:\s*"([0-9a-f]{7})`)
	bunPkg     = lazyre.New(`^    "[^"]+": \["(@?[^@"]+)@([^"]+)"`)
)

// textLocks are the lockfiles listed as one "name version" line per package:
// how to recognise the text, its label and the parser of its lines.
var textLocks = []struct {
	label string
	is    func(text string) bool
	parse func(lines []string) []string
}{
	{"pnpm-lock.yaml", func(t string) bool {
		return strings.Contains(t, "lockfileVersion: ") && strings.Contains(t, "\npackages:\n")
	}, pnpmLock},
	{"pubspec.lock", func(t string) bool { return strings.HasPrefix(t, "# Generated by pub") }, pubspecLock},
	{"mix.lock", func(t string) bool { return strings.HasPrefix(t, "%{\n") }, mixLock},
	{"Podfile.lock", func(t string) bool { return strings.HasPrefix(t, "PODS:\n") }, podfileLock},
	{"Package.resolved", func(t string) bool { return strings.Contains(t, `"pins"`) }, swiftResolved},
	{"bun.lock", func(t string) bool {
		return strings.Contains(t, `"lockfileVersion"`) && strings.Contains(t, `"packages": {`)
	}, bunLock},
}

// textLock lists the packages of a lockfile in textLocks; nil for any other text.
func textLock(text string, lines []string) []string {
	for _, l := range textLocks {
		if !l.is(text) {
			continue
		}
		pkgs := l.parse(lines)
		if len(pkgs) == 0 {
			return nil
		}
		return append([]string{fmt.Sprintf("%s: %d packages (hashes, sources and dependency lists dropped)", l.label, len(pkgs))}, pkgs...)
	}
	return nil
}

// pkgSet collects "name version" lines, each once.
type pkgSet struct {
	seen map[string]bool
	out  []string
}

func (s *pkgSet) add(name, version string) {
	key := name + " " + version
	if s.seen == nil {
		s.seen = map[string]bool{}
	}
	if !s.seen[key] {
		s.seen[key] = true
		s.out = append(s.out, key)
	}
}

// pnpmLock reads the keys of the packages: section (one document per file or several).
func pnpmLock(lines []string) []string {
	var s pkgSet
	in := false
	for _, l := range lines {
		if l != "" && l[0] != ' ' && l[0] != '#' {
			in = l == "packages:"
			continue
		}
		if m := pnpmPkg.FindStringSubmatch(l); in && m != nil {
			s.add(m[1], m[2])
		}
	}
	return s.out
}

// pubspecLock pairs each package key with its version line.
func pubspecLock(lines []string) []string {
	var s pkgSet
	name := ""
	for _, l := range lines {
		if m := pubName.FindStringSubmatch(l); m != nil {
			name = m[1]
		} else if m := pubVer.FindStringSubmatch(l); m != nil && name != "" {
			s.add(name, m[1])
		}
	}
	return s.out
}

// mixLock reads hex packages by version and git ones by short commit.
func mixLock(lines []string) []string {
	var s pkgSet
	for _, l := range lines {
		if m := mixHex.FindStringSubmatch(l); m != nil {
			s.add(m[1], m[2])
		} else if m := mixGit.FindStringSubmatch(l); m != nil {
			s.add(m[1], m[2])
		}
	}
	return s.out
}

// podfileLock reads the PODS section, whose top-level entries carry the
// resolved versions; the dependency edges below them are dropped.
func podfileLock(lines []string) []string {
	var s pkgSet
	for _, l := range lines[1:] {
		if l != "" && l[0] != ' ' {
			break
		}
		if m := podSpec.FindStringSubmatch(l); m != nil {
			s.add(m[1], m[2])
		}
	}
	return s.out
}

// swiftResolved reads pins (v1 "package", v2/v3 "identity"): version, else
// branch, else short revision.
func swiftResolved(lines []string) []string {
	var s pkgSet
	name, version, branch, rev := "", "", "", ""
	flush := func() {
		if name != "" {
			s.add(name, cmp.Or(version, branch, rev))
		}
		version, branch, rev = "", "", ""
	}
	for _, l := range lines {
		if m := spmName.FindStringSubmatch(l); m != nil {
			flush()
			name = m[1]
		} else if m := spmVersion.FindStringSubmatch(l); m != nil {
			version = m[1]
		} else if m := spmBranch.FindStringSubmatch(l); m != nil {
			branch = m[1]
		} else if m := spmRev.FindStringSubmatch(l); m != nil {
			rev = m[1]
		}
	}
	flush()
	return s.out
}

// bunLock reads the first element of each packages entry: "name@version".
func bunLock(lines []string) []string {
	var s pkgSet
	for _, l := range lines {
		if m := bunPkg.FindStringSubmatch(l); m != nil {
			s.add(m[1], m[2])
		}
	}
	return s.out
}
