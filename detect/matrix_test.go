func TestDialectMatrix(t *testing.T) {
	for _, s := range specs {
		if len(s.Cmds) > 0 || s.CmdFunc != nil {
			cmd, ok := cmdExamples[s.Type]
			if !ok {
				t.Errorf("%s: no command example", s.Type)
			} else if got := FromCmd(cmd); got != s.Type {
				t.Errorf("%s: command %q detected as %q", s.Type, cmd, got)
			}
		}
		if s.Sniff == nil {
			continue
		}
		text, ok := sniffInline[s.Type]
		if f, isFile := sniffFixtures[s.Type]; isFile {
			b, err := os.ReadFile("../testdata/eval/" + f)
			if err != nil {
				t.Fatal(err)
			}
			text, ok = string(b), true
		}
		if !ok {
			t.Errorf("%s: no content example", s.Type)
		} else if got := Sniff(text); got != s.Type {
			t.Errorf("%s: content sniffed as %q", s.Type, got)
		}
	}
}
